"""Render the management report as self-contained HTML (for people) and Markdown (for Git/chat)."""
from __future__ import annotations

import html
from datetime import datetime

import pandas as pd

from reporting.alerts import Alert
from reporting.data import ReportData

BADGE = {"CRITICAL": "#C0392B", "HIGH": "#E67E22", "MEDIUM": "#D4AC0D", "INFO": "#5D6D7E"}


def _money(v) -> str:
    return "-" if v is None or pd.isna(v) else f"{v:,.0f} ₾"


def _pct(v) -> str:
    return "-" if v is None or pd.isna(v) else f"{v:+.1f}%"


def kpi_cards(data: ReportData) -> list[tuple[str, str, str]]:
    """(label, value, comparison) for the headline cards: comparable year-to-date."""
    y = data.row("ytd")
    if not y:
        return []
    return [
        ("Revenue YTD", _money(y["ytd_revenue"]), f"{_pct(y['revenue_yoy_pct'])} vs prior YTD"),
        ("Orders YTD", f"{y['ytd_orders']:,.0f}", f"{_pct(y['orders_yoy_pct'])} vs prior YTD"),
        ("Avg order value", _money(y["ytd_avg_order_value"]), f"prior {_money(y['prior_ytd_avg_order_value'])}"),
        ("Profit margin YTD", f"{y['ytd_margin_pct']:.1f}%", f"prior {y['prior_ytd_margin_pct']:.1f}%"),
        ("Service revenue YTD", _money(y["ytd_service_revenue"]), f"{_pct(y['service_revenue_yoy_pct'])} vs prior YTD"),
    ]


def branch_table(data: ReportData) -> pd.DataFrame:
    b = data["branches"]
    return pd.DataFrame({
        "Branch": b.branch_name,
        "Revenue YTD": b.ytd_revenue.map(_money),
        "YTD vs LY": b.ytd_yoy_pct.map(_pct),
        "Last 3M vs LY": b.last_3m_yoy_pct.map(_pct),
        "Trend": b.trend_status,
        "Negative feedback (this year)": b.negative_rate_current_year_pct.map(lambda v: "-" if pd.isna(v) else f"{v:.1f}%"),
        "Avg rating": b.avg_rating.map(lambda v: "-" if pd.isna(v) else f"{v:.2f}"),
    })


def complaint_table(data: ReportData) -> pd.DataFrame:
    c = data["complaints"]
    return pd.DataFrame({
        "Topic": c.topic, "Negative comments (all time)": c.negative_count.astype(int),
        "Latest quarter": c.negatives_latest_quarter.astype(int),
        "Same quarter last year": c.negatives_same_quarter_last_year.astype(int),
    })


def insight(data: ReportData) -> tuple[list[str], str]:
    """Company-level AI insight split into bullet lines, plus its provenance."""
    row = data.row("insight")
    if not row:
        return [], ""
    lines = [ln.strip().lstrip("*-• ").strip() for ln in row["insight_text"].splitlines() if ln.strip()]
    return lines, f"{row['period_label']} · generated by {row['method']} ({row['model']}) from SQL facts"


def run_footer(data: ReportData, generated_at: datetime) -> str:
    run, dq = data.row("last_run"), data.row("dq_summary")
    parts = [f"Generated {generated_at:%Y-%m-%d %H:%M}"]
    if run:
        parts.append(f"pipeline run {run['run_id']}: {run['status']}")
    if dq:
        parts.append(f"{dq['checks']} quality checks, {dq['critical_failures']} critical, {dq['warnings']} warnings")
    period = data.row("period")
    if period:
        parts.append(f"data {period['first_date']} – {period['last_date']}")
    return " · ".join(parts)


# ---------------------------------------------------------------- Markdown
def to_markdown(data: ReportData, alerts: list[Alert], generated_at: datetime, title: str) -> str:
    out = [f"# {title}", "", f"_{run_footer(data, generated_at)}_", "", "## Alerts", ""]
    out += [f"- **{a.severity}** · {a.area}: {a.message}" for a in alerts] or ["- No alerts."]
    out += ["", "## Headline KPIs (comparable year-to-date)", "", "| KPI | Value | Comparison |", "|---|---:|---|"]
    out += [f"| {label} | {value} | {cmp} |" for label, value, cmp in kpi_cards(data)]
    out += ["", "## Branches", "", branch_table(data).to_markdown(index=False)]
    lines, source = insight(data)
    if lines:
        out += ["", "## AI summary of customer feedback", ""] + [f"- {ln}" for ln in lines] + ["", f"_{source}_"]
    out += ["", "## Top complaint topics", "", complaint_table(data).to_markdown(index=False)]
    crit = data["dq_critical"]
    if len(crit):
        out += ["", "## Failed critical checks", "", crit.to_markdown(index=False)]
    return "\n".join(out) + "\n"


