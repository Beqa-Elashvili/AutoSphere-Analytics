def _table(df: pd.DataFrame) -> str:
    head = "".join(f"<th>{html.escape(str(c))}</th>" for c in df.columns)
    rows = []
    for rec in df.itertuples(index=False):
        cells = []
        for col, val in zip(df.columns, rec):
            cls = f' class="{val}"' if col == "Trend" else ""
            cells.append(f"<td{cls}>{html.escape(str(val))}</td>")
        rows.append("<tr>" + "".join(cells) + "</tr>")
    return f"<table><tr>{head}</tr>{''.join(rows)}</table>"


def to_html(data: ReportData, alerts: list[Alert], generated_at: datetime, title: str,
            failure: str | None = None) -> str:
    e = html.escape
    parts = [f"<!doctype html><html lang='en'><head><meta charset='utf-8'>"
             f"<meta name='viewport' content='width=device-width,initial-scale=1'><title>{e(title)}</title>"
             f"<style>{CSS}</style></head><body><div class='wrap'>",
             f"<h1>{e(title)}</h1><div class='meta'>{e(run_footer(data, generated_at))}</div>"]
    if failure:
        parts.append(f"<div class='banner'>Refresh failed: {e(failure)}</div>")
    parts.append("<h2>Alerts</h2>")
    for a in alerts:
        color = BADGE[a.severity]
        parts.append(f"<div class='alert' style='border-color:{color}'><span class='badge' style='background:{color}'>"
                     f"{a.severity}</span><b>{e(a.area)}</b> · {e(a.message)}</div>")
    if not alerts:
        parts.append("<div class='box'>No alerts.</div>")
    parts.append("<h2>Headline KPIs (comparable year-to-date)</h2><div class='cards'>")
    parts += [f"<div class='card'><div class='l'>{e(l)}</div><div class='v'>{e(v)}</div><div class='c'>{e(c)}</div></div>"
              for l, v, c in kpi_cards(data)]
    parts.append("</div><h2>Branches</h2>" + _table(branch_table(data)))
    lines, source = insight(data)
    if lines:
        parts.append("<h2>AI summary of customer feedback</h2><div class='box'><ul>"
                     + "".join(f"<li>{e(ln)}</li>" for ln in lines)
                     + f"</ul><div class='meta'>{e(source)}</div></div>")
    parts.append("<h2>Top complaint topics</h2>" + _table(complaint_table(data)))
    crit = data["dq_critical"]
    if len(crit):
        parts.append("<h2>Failed critical checks</h2>" + _table(crit))
    parts.append("<p class='meta'>Figures come from the PostgreSQL analytics layer (same definitions as the "
                 "Power BI report). Synthetic data, AutoSphere Analytics portfolio project.</p></div></body></html>")
    return "\n".join(parts)
